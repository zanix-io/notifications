import gulp from 'npm:gulp@^5.0.1'
import handlebars from 'npm:gulp-handlebars@^5.0.2'
import rename from 'npm:gulp-rename@^2.1.0'
import wrap from 'npm:gulp-wrap@^0.15.0'
import { dirname, join, relative } from '@std/path'

const HANDLEBARS_ROOT = 'src/modules/templates/handlebars'
const GENERATED_CODE_TEMPLATES_PATH = 'src/modules/templates/db/code-templates.generated.ts'

function templates() {
  // `{channel, name}` pairs discovered below, one per `.hbs` actually compiled — written out as
  // `CODE_TEMPLATES` once the whole stream finishes (see `writeGeneratedCodeTemplates()`), instead
  // of being maintained by hand in `db/manifest.ts` (see `docs/templates.md`'s "Adding a custom
  // template" section).
  const discovered: { channel: string; name: string }[] = []

  return gulp.src(`${HANDLEBARS_ROOT}/**/*.hbs`, { base: './' })
    .pipe(handlebars())
    .pipe(
      wrap(function ({ file, contents }: { file: { path: string }; contents: ArrayBuffer }) {
        const templateDir = dirname(file.path)
        const cssContent = Deno.readTextFileSync(join(templateDir, 'styles.css'))
        // Read the original `.hbs` by its known, fixed filename rather than `file.path` itself —
        // by the time this callback runs, `file.path` may already reflect `rename()`'s `.js`
        // extension (`rename()` is declared after `wrap()` in the pipe chain, but gulp's stream
        // processing doesn't guarantee that ordering holds for a given vinyl file's `.path` by the
        // time this callback fires). Its raw text is what a database sync seeds `ZanixTemplate.hbs`
        // with, since the `compiled` bytecode above can't be used for that (see `docs/templates.md`).
        const rawSource = Deno.readTextFileSync(join(templateDir, 'main.hbs'))

        // `{channel}/{name}` relative to the handlebars root — exactly the pair `CODE_TEMPLATES`
        // needs, discovered here instead of hand-maintained.
        const [channel, name] = relative(HANDLEBARS_ROOT, templateDir).split('/')
        discovered.push({ channel, name })

        return `// deno-coverage-ignore-file
/**
 * This file is autogenerated by a build or script process.
 * It has not been manually modified and should not be altered directly.
 * Any changes to the generated content should be made through the
 * corresponding source files or template configurations.
 */
import Handlebars from "handlebars/runtime.js";
import TemplateDataSchema from './schema.ts'

const compiled = Handlebars.template(${contents.toString()});

export default function(context) {
  try{
    const data = TemplateDataSchema.parse(context);
    data.styles.css = \`\\n${cssContent}\` + '\\n' + data.styles.css
    return compiled(data);
  } catch (e) {
    throw new Error(e.message)
  }
}

// Raw source, for database-sync seeding — see \`db/manifest.ts\`.
export const source = ${JSON.stringify(rawSource)};
export const styles = ${JSON.stringify(cssContent)};
    `
      }),
    )
    .pipe(rename({ extname: '.js' }))
    .pipe(gulp.dest('./'))
    .on('end', () => writeGeneratedCodeTemplates(discovered))
}

/**
 * Writes `db/code-templates.generated.ts`'s `CODE_TEMPLATES` from every `{channel, name}`
 * discovered above — sorted for a stable diff regardless of `gulp.src()`'s glob order.
 */
function writeGeneratedCodeTemplates(entries: { channel: string; name: string }[]): void {
  const sorted = [...entries].sort((a, b) =>
    `${a.channel}:${a.name}`.localeCompare(`${b.channel}:${b.name}`)
  )
  const body = sorted.map(({ channel, name }) => `  { channel: '${channel}', name: '${name}' },`)
    .join('\n')

  Deno.writeTextFileSync(
    GENERATED_CODE_TEMPLATES_PATH,
    `// deno-coverage-ignore-file
/**
 * This file is autogenerated by \`deno task build-handlebars\` (see \`handlebars/compiler.ts\`).
 * It has not been manually modified and should not be altered directly — add a new base
 * template's \`.hbs\`/\`schema.ts\`/\`styles.css\` under \`handlebars/{channel}/{name}/\` and rerun
 * the build task instead (see \`docs/templates.md\`'s "Adding a custom template" section).
 */
import type { Notifiers } from 'typings/general.ts'

/**
 * The full list of \`{channel, name}\` pairs that own a real \`.hbs\` file in source
 * (\`handlebars/{channel}/{name}/\`) — the only templates a database sync can seed from or resync
 * against. Discovered directly from which \`main.hbs\` files exist, not maintained by hand.
 */
export const CODE_TEMPLATES: ReadonlyArray<{ channel: Notifiers; name: string }> = [
${body}
]
`,
  )
}

templates()
